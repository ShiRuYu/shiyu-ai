-- MAGMA-based platform memory. One event participates in multiple relation graphs.
CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."MEMORY_EVENT" (
    "ID" CHARACTER VARYING(64) NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "NAMESPACE" CHARACTER VARYING(64) NOT NULL,
    "SUBJECT_TYPE" CHARACTER VARYING(64) NOT NULL,
    "SUBJECT_ID" CHARACTER VARYING(128) NOT NULL,
    "EVENT_TYPE" CHARACTER VARYING(64) NOT NULL,
    "CONTENT" CHARACTER LARGE OBJECT NOT NULL,
    "OCCURRED_AT" TIMESTAMP NOT NULL,
    "SOURCE_TYPE" CHARACTER VARYING(64),
    "SOURCE_ID" CHARACTER VARYING(128),
    "ATTRIBUTES" CHARACTER LARGE OBJECT,
    "CONFIDENCE" DOUBLE NOT NULL,
    "IMPORTANCE" DOUBLE NOT NULL,
    "STATUS" CHARACTER VARYING(16) NOT NULL,
    "CONFIRMATION_POLICY" CHARACTER VARYING(16) NOT NULL,
    "CREATED_AT" TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP NOT NULL,
    CONSTRAINT "PK_MEMORY_EVENT" PRIMARY KEY ("ID")
);
CREATE INDEX IF NOT EXISTS "IDX_MEMORY_EVENT_SUBJECT" ON "PUBLIC"."MEMORY_EVENT"("TENANT_ID", "NAMESPACE", "SUBJECT_TYPE", "SUBJECT_ID", "OCCURRED_AT");
CREATE INDEX IF NOT EXISTS "IDX_MEMORY_EVENT_STATUS" ON "PUBLIC"."MEMORY_EVENT"("TENANT_ID", "STATUS");

CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."MEMORY_ENTITY" (
    "ID" CHARACTER VARYING(64) NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "ENTITY_TYPE" CHARACTER VARYING(64) NOT NULL,
    "EXTERNAL_REF" CHARACTER VARYING(255) NOT NULL,
    "DISPLAY_NAME" CHARACTER VARYING(255),
    "NORMALIZED_NAME" CHARACTER VARYING(255),
    "ATTRIBUTES" CHARACTER LARGE OBJECT,
    "ACTIVE" BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT "PK_MEMORY_ENTITY" PRIMARY KEY ("ID"),
    CONSTRAINT "UK_MEMORY_ENTITY_REF" UNIQUE ("TENANT_ID", "ENTITY_TYPE", "EXTERNAL_REF")
);

CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."MEMORY_EDGE" (
    "ID" CHARACTER VARYING(64) NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "SOURCE_NODE_ID" CHARACTER VARYING(64) NOT NULL,
    "TARGET_NODE_ID" CHARACTER VARYING(64) NOT NULL,
    "GRAPH_TYPE" CHARACTER VARYING(16) NOT NULL,
    "RELATION_TYPE" CHARACTER VARYING(64) NOT NULL,
    "DIRECTED" BOOLEAN NOT NULL,
    "WEIGHT" DOUBLE NOT NULL,
    "CONFIDENCE" DOUBLE NOT NULL,
    "ORIGIN" CHARACTER VARYING(16) NOT NULL,
    "EVIDENCE_SOURCE" CHARACTER VARYING(255),
    "ACTIVE" BOOLEAN NOT NULL DEFAULT TRUE,
    "CREATED_AT" TIMESTAMP NOT NULL,
    CONSTRAINT "PK_MEMORY_EDGE" PRIMARY KEY ("ID")
);
CREATE INDEX IF NOT EXISTS "IDX_MEMORY_EDGE_SOURCE" ON "PUBLIC"."MEMORY_EDGE"("TENANT_ID", "SOURCE_NODE_ID", "GRAPH_TYPE", "ACTIVE");
CREATE INDEX IF NOT EXISTS "IDX_MEMORY_EDGE_TARGET" ON "PUBLIC"."MEMORY_EDGE"("TENANT_ID", "TARGET_NODE_ID", "GRAPH_TYPE", "ACTIVE");

CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."MEMORY_CONSOLIDATION_JOB" (
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "EVENT_ID" CHARACTER VARYING(64) NOT NULL,
    "STATUS" CHARACTER VARYING(16) NOT NULL DEFAULT 'PENDING',
    "ATTEMPTS" INTEGER NOT NULL DEFAULT 0,
    "AVAILABLE_AT" TIMESTAMP NOT NULL,
    "LEASED_UNTIL" TIMESTAMP,
    "LAST_ERROR" CHARACTER VARYING(2000),
    "CREATED_AT" TIMESTAMP NOT NULL,
    "UPDATED_AT" TIMESTAMP NOT NULL,
    CONSTRAINT "PK_MEMORY_CONSOLIDATION_JOB" PRIMARY KEY ("ID")
);
CREATE INDEX IF NOT EXISTS "IDX_MEMORY_JOB_STATUS" ON "PUBLIC"."MEMORY_CONSOLIDATION_JOB"("STATUS", "AVAILABLE_AT");

CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."MEMORY_RETRIEVAL_TRACE" (
    "ID" CHARACTER VARYING(64) NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "NAMESPACE" CHARACTER VARYING(64) NOT NULL,
    "QUERY_TEXT" CHARACTER LARGE OBJECT NOT NULL,
    "ANCHOR_EVENT_IDS" CHARACTER LARGE OBJECT,
    "CREATED_AT" TIMESTAMP NOT NULL,
    CONSTRAINT "PK_MEMORY_RETRIEVAL_TRACE" PRIMARY KEY ("ID")
);
CREATE INDEX IF NOT EXISTS "IDX_MEMORY_TRACE_TENANT" ON "PUBLIC"."MEMORY_RETRIEVAL_TRACE"("TENANT_ID", "CREATED_AT");
