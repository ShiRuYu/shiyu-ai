package com.shiyu.ai.agent.implementation.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verifyNoInteractions;

import com.shiyu.ai.agent.implementation.domain.model.AuditLogBO;
import com.shiyu.ai.agent.implementation.event.publisher.EventPublisher;
import com.shiyu.ai.agent.implementation.port.repository.AuditLogRepository;
import com.shiyu.ai.kernel.context.TenantId;
import com.shiyu.ai.kernel.context.TenantScope;

import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;

/** Verifies required audit records reach H2 and join the caller's transaction. */
class AuditServicePersistenceIntegrationTest {
    private EmbeddedDatabase database;
    private JdbcTemplate jdbc;

    @BeforeEach
    void setUp() {
        database = new EmbeddedDatabaseBuilder()
                .generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2)
                .build();
        jdbc = new JdbcTemplate(database);
        jdbc.execute("""
                CREATE TABLE observation_audit_log (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tenant_id BIGINT NOT NULL,
                    user_id BIGINT NOT NULL,
                    action VARCHAR(64) NOT NULL,
                    target_type VARCHAR(64),
                    target_id VARCHAR(128),
                    detail VARCHAR,
                    ip VARCHAR(64),
                    result VARCHAR(16),
                    error_msg VARCHAR(500),
                    duration_ms BIGINT,
                    create_time TIMESTAMP
                )
                """);
        jdbc.execute("CREATE TABLE manual_resolution (id BIGINT PRIMARY KEY, completed BOOLEAN NOT NULL)");
    }

    @AfterEach
    void tearDown() {
        TenantScope.clear();
        database.shutdown();
    }

    @Test
    void requiredAuditRecordIsWrittenToH2WithTenantAndActionDetails() {
        EventPublisher publisher = mock(EventPublisher.class);
        AuditService service = new AuditService(publisher, jdbcRepository());

        service.recordSuccessRequired(
                new TenantId(7L),
                9L,
                "127.0.0.1",
                "TOOL_APPROVAL_MANUAL_RECONCILIATION",
                "TOOL_APPROVAL",
                "approval-1",
                java.util.Map.of("runId", "run-1", "source", "MANUAL_RECONCILIATION"));

        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM observation_audit_log", Integer.class));
        assertEquals(7L, jdbc.queryForObject("SELECT tenant_id FROM observation_audit_log", Long.class));
        assertEquals(9L, jdbc.queryForObject("SELECT user_id FROM observation_audit_log", Long.class));
        assertEquals(
                "TOOL_APPROVAL_MANUAL_RECONCILIATION",
                jdbc.queryForObject("SELECT action FROM observation_audit_log", String.class));
        assertEquals("approval-1", jdbc.queryForObject("SELECT target_id FROM observation_audit_log", String.class));
        String detail = jdbc.queryForObject("SELECT detail FROM observation_audit_log", String.class);
        assertTrue(detail.contains("\"runId\":\"run-1\""));
        assertTrue(detail.contains("\"source\":\"MANUAL_RECONCILIATION\""));
        verifyNoInteractions(publisher);
    }

    @Test
    void auditConstraintFailureRollsBackTheCallerBusinessTransaction() {
        EventPublisher publisher = mock(EventPublisher.class);
        AuditService service = new AuditService(publisher, jdbcRepository());
        TransactionTemplate transaction = new TransactionTemplate(new DataSourceTransactionManager(database));

        assertThrows(
                DataIntegrityViolationException.class,
                () -> transaction.executeWithoutResult(status -> {
                    jdbc.update("INSERT INTO manual_resolution(id, completed) VALUES (?, ?)", 1L, true);
                    service.recordSuccessRequired(
                            new TenantId(7L),
                            9L,
                            null,
                            "X".repeat(65),
                            "TOOL_APPROVAL",
                            "approval-1",
                            java.util.Map.of("runId", "run-1"));
                }));

        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM manual_resolution", Integer.class));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM observation_audit_log", Integer.class));
        verifyNoInteractions(publisher);
    }

    private AuditLogRepository jdbcRepository() {
        return (tenantId, record) -> {
            TenantScope.requireMatches(tenantId);
            jdbc.update(
                    """
                    INSERT INTO observation_audit_log
                        (tenant_id, user_id, action, target_type, target_id, detail, ip,
                         result, error_msg, duration_ms, create_time)
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    record.getTenantId(),
                    record.getUserId(),
                    record.getAction(),
                    record.getTargetType(),
                    record.getTargetId(),
                    record.getDetail(),
                    record.getIp(),
                    record.getResult(),
                    record.getErrorMsg(),
                    record.getDurationMs(),
                    record.getCreateTime());
        };
    }
}
