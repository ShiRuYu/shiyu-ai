package com.shiyu.ai.agent.implementation.checkpoint;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertNull;

import com.shiyu.ai.agent.contract.node.NodeActorContext;
import com.shiyu.ai.agent.implementation.domain.model.AgentCheckpointBO;
import com.shiyu.ai.agent.implementation.port.repository.AgentCheckpointRepository;
import com.shiyu.ai.kernel.context.ActorContext;
import com.shiyu.ai.kernel.context.TenantId;
import com.shiyu.ai.kernel.context.UserId;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;

import java.nio.file.Path;
import java.util.List;
import java.util.Map;

/** 验证新数据库连接能完整恢复图检查点且内部身份不会落库。 */
class DbCheckpointStoreRestartTest {
    @TempDir Path directory;

    @Test
    void stableCheckpointIdAndNextNodeSurviveDatabaseRestart() {
        String url = "jdbc:h2:file:" + directory.resolve("checkpoints").toAbsolutePath()
                .toString().replace('\\', '/')
                + ";MODE=PostgreSQL";
        TenantId tenant = new TenantId(9L);
        ActorContext actor = new ActorContext(tenant, new UserId(7L), false);
        JdbcTemplate firstConnection = jdbc(url);
        firstConnection.execute("CREATE TABLE checkpoint (id BIGINT GENERATED BY DEFAULT "
                + "AS IDENTITY PRIMARY KEY, tenant_id BIGINT, checkpoint_id VARCHAR(64), "
                + "execution_id VARCHAR(64), node_id VARCHAR(64), state_data CLOB, "
                + "create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP)");
        Checkpoint expected = new Checkpoint(tenant, "exec-1", "cp-1", "effect", "finish",
                Map.of("effect", "completed", "studentId", 42L,
                        "nested", List.of(Map.of("parentId", Long.MAX_VALUE)),
                        NodeActorContext.KEY, actor));
        new DbCheckpointStore(new JdbcRepository(firstConnection)).save(tenant, expected);

        JdbcTemplate restartedConnection = jdbc(url);
        DbCheckpointStore restarted = new DbCheckpointStore(new JdbcRepository(restartedConnection));
        Checkpoint restored = restarted.loadByExecutionId(tenant, "exec-1");

        assertEquals("cp-1", restored.getCheckpointId());
        assertEquals("effect", restored.getNodeId());
        assertEquals("finish", restored.getNextNodeId());
        assertEquals("completed", restored.getState().get("effect"));
        assertEquals(Long.class, restored.getState().get("studentId").getClass());
        assertEquals(42L, restored.getState().get("studentId"));
        assertEquals(Long.class, ((Map<?, ?>) ((List<?>) restored.getState().get("nested"))
                .get(0)).get("parentId").getClass());
        assertEquals(Long.MAX_VALUE, ((Map<?, ?>) ((List<?>) restored.getState().get("nested"))
                .get(0)).get("parentId"));
        assertFalse(restored.getState().containsKey(NodeActorContext.KEY));
        assertNull(restarted.loadByExecutionId(new TenantId(10L), "exec-1"));

        restarted.save(tenant, new Checkpoint(tenant, "exec-1", "cp-2",
                "__agent_node_started__", "finish", Map.of("effect", "completed")));
        restartedConnection.update("UPDATE checkpoint SET create_time = "
                + "TIMESTAMP '2026-01-01 00:00:00' WHERE execution_id = ?", "exec-1");
        Checkpoint latest = new DbCheckpointStore(new JdbcRepository(jdbc(url)))
                .loadByExecutionId(tenant, "exec-1");
        assertEquals("cp-2", latest.getCheckpointId());
        assertEquals("__agent_node_started__", latest.getNodeId());

        restartedConnection.update("INSERT INTO checkpoint (tenant_id, checkpoint_id, "
                        + "execution_id, node_id, state_data) VALUES (?, ?, ?, ?, ?)",
                tenant.value(), "old-cp", "old-exec", "effect",
                "{\"__agentCheckpointFormat\":\"langgraph4j-v1\","
                        + "\"nextNodeId\":\"finish\",\"state\":{\"studentId\":42}}");
        Checkpoint untyped = restarted.loadByExecutionId(tenant, "old-exec");
        assertNull(untyped.getNextNodeId());
    }

    private JdbcTemplate jdbc(String url) {
        DriverManagerDataSource dataSource = new DriverManagerDataSource();
        dataSource.setDriverClassName("org.h2.Driver");
        dataSource.setUrl(url);
        return new JdbcTemplate(dataSource);
    }

    /** 只提供测试所需的真实 SQL 读写，保存逻辑由 DbCheckpointStore 执行。 */
    private static final class JdbcRepository implements AgentCheckpointRepository {
        private final JdbcTemplate jdbc;

        private JdbcRepository(JdbcTemplate jdbc) {
            this.jdbc = jdbc;
        }

        @Override
        public void insert(TenantId tenantId, AgentCheckpointBO checkpoint) {
            jdbc.update("INSERT INTO checkpoint (tenant_id, checkpoint_id, execution_id, "
                            + "node_id, state_data) VALUES (?, ?, ?, ?, ?)",
                    tenantId.value(), checkpoint.getCheckpointId(), checkpoint.getExecutionId(),
                    checkpoint.getNodeId(), checkpoint.getStateData());
        }

        @Override
        public AgentCheckpointBO selectByCheckpointId(TenantId tenantId, String checkpointId) {
            List<AgentCheckpointBO> rows = jdbc.query("SELECT * FROM checkpoint WHERE tenant_id = ? "
                            + "AND checkpoint_id = ?", (rs, row) -> map(rs),
                    tenantId.value(), checkpointId);
            return rows.isEmpty() ? null : rows.get(0);
        }

        @Override
        public AgentCheckpointBO selectLatestByExecutionId(TenantId tenantId, String executionId) {
            List<AgentCheckpointBO> rows = jdbc.query("SELECT * FROM checkpoint WHERE tenant_id = ? "
                            + "AND execution_id = ? ORDER BY create_time DESC, id DESC LIMIT 1",
                    (rs, row) -> map(rs), tenantId.value(), executionId);
            return rows.isEmpty() ? null : rows.get(0);
        }

        @Override
        public void deleteByCheckpointId(TenantId tenantId, String checkpointId) {
            jdbc.update("DELETE FROM checkpoint WHERE tenant_id = ? AND checkpoint_id = ?",
                    tenantId.value(), checkpointId);
        }

        @Override
        public void deleteByExecutionId(TenantId tenantId, String executionId) {
            jdbc.update("DELETE FROM checkpoint WHERE tenant_id = ? AND execution_id = ?",
                    tenantId.value(), executionId);
        }

        @Override
        public List<AgentCheckpointBO> listByExecutionId(TenantId tenantId, String executionId) {
            return jdbc.query("SELECT * FROM checkpoint WHERE tenant_id = ? AND execution_id = ?",
                    (rs, row) -> map(rs), tenantId.value(), executionId);
        }

        private AgentCheckpointBO map(java.sql.ResultSet rs) throws java.sql.SQLException {
            AgentCheckpointBO row = new AgentCheckpointBO();
            row.setTenantId(rs.getLong("tenant_id"));
            row.setCheckpointId(rs.getString("checkpoint_id"));
            row.setExecutionId(rs.getString("execution_id"));
            row.setNodeId(rs.getString("node_id"));
            row.setStateData(rs.getString("state_data"));
            return row;
        }
    }
}
