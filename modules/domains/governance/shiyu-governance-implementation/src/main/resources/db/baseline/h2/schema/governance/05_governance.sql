
CREATE CACHED TABLE "PUBLIC"."GOVERNANCE_USAGE_RECORD" (
    "ID" CHARACTER VARYING(64) NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "USER_ID" BIGINT NOT NULL,
    "CORRELATION_ID" CHARACTER VARYING(128) NOT NULL,
    "SOURCE_TYPE" CHARACTER VARYING(64) NOT NULL,
    "SOURCE_ID" CHARACTER VARYING(128) NOT NULL,
    "INPUT_TOKENS" BIGINT DEFAULT 0 NOT NULL,
    "OUTPUT_TOKENS" BIGINT DEFAULT 0 NOT NULL,
    "COST" DECIMAL(20, 8) DEFAULT 0 NOT NULL,
    "OCCURRED_AT" TIMESTAMP NOT NULL,
    "USAGE_TYPE" CHARACTER VARYING(32) DEFAULT 'METERED' NOT NULL,
    "LATENCY_MS" BIGINT,
    "SESSION_ID" CHARACTER VARYING(128),
    "EXT_INFO" CHARACTER LARGE OBJECT,
    "CREATE_TIME" TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT "PK_GOVERNANCE_USAGE_RECORD" PRIMARY KEY ("ID"),
    CONSTRAINT "UK_GOVERNANCE_USAGE_SOURCE" UNIQUE ("TENANT_ID", "SOURCE_TYPE", "SOURCE_ID"),
    CONSTRAINT "CK_GOVERNANCE_USAGE_INPUT" CHECK ("INPUT_TOKENS" >= 0),
    CONSTRAINT "CK_GOVERNANCE_USAGE_OUTPUT" CHECK ("OUTPUT_TOKENS" >= 0),
    CONSTRAINT "CK_GOVERNANCE_USAGE_COST" CHECK ("COST" >= 0)
);

CREATE INDEX "PUBLIC"."IDX_GOVERNANCE_USAGE_TENANT_TIME"
    ON "PUBLIC"."GOVERNANCE_USAGE_RECORD" ("TENANT_ID", "OCCURRED_AT");

CREATE INDEX "PUBLIC"."IDX_GOVERNANCE_USAGE_TENANT_USER_TIME"
    ON "PUBLIC"."GOVERNANCE_USAGE_RECORD" ("TENANT_ID", "USER_ID", "OCCURRED_AT");

CREATE CACHED TABLE "PUBLIC"."GOVERNANCE_QUOTA_TENANT" (
    "TENANT_ID" BIGINT NOT NULL,
    "DAY_START" DATE NOT NULL,
    "MINUTE_START_EPOCH_SECOND" BIGINT NOT NULL,
    "TOKENS_USED" BIGINT DEFAULT 0 NOT NULL,
    "TOKENS_RESERVED" BIGINT DEFAULT 0 NOT NULL,
    "REQUESTS_THIS_MINUTE" BIGINT DEFAULT 0 NOT NULL,
    "ACTIVE_RESERVATIONS" INTEGER DEFAULT 0 NOT NULL,
    CONSTRAINT "PK_GOVERNANCE_QUOTA_TENANT" PRIMARY KEY ("TENANT_ID"),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_TOKENS_USED" CHECK ("TOKENS_USED" >= 0),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_TOKENS_RESERVED" CHECK ("TOKENS_RESERVED" >= 0),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_REQUESTS" CHECK ("REQUESTS_THIS_MINUTE" >= 0),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_ACTIVE" CHECK ("ACTIVE_RESERVATIONS" >= 0)
);

CREATE CACHED TABLE "PUBLIC"."GOVERNANCE_QUOTA_RESERVATION" (
    "ID" BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
    "TENANT_ID" BIGINT NOT NULL,
    "REFERENCE_KEY" CHARACTER VARYING(128),
    "RESERVED_ON_DATE" DATE NOT NULL,
    "ESTIMATED_TOKENS" INTEGER NOT NULL,
    "STATUS" CHARACTER VARYING(16) NOT NULL,
    "CREATED_AT_EPOCH_MILLIS" BIGINT NOT NULL,
    "EXPIRES_AT_EPOCH_MILLIS" BIGINT NOT NULL,
    CONSTRAINT "PK_GOVERNANCE_QUOTA_RESERVATION" PRIMARY KEY ("ID"),
    CONSTRAINT "UK_GOVERNANCE_QUOTA_REFERENCE" UNIQUE ("TENANT_ID", "REFERENCE_KEY"),
    CONSTRAINT "FK_GOVERNANCE_QUOTA_RESERVATION_TENANT"
        FOREIGN KEY ("TENANT_ID") REFERENCES "PUBLIC"."GOVERNANCE_QUOTA_TENANT" ("TENANT_ID"),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_ESTIMATED" CHECK ("ESTIMATED_TOKENS" >= 0),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_STATUS"
        CHECK ("STATUS" IN ('ACTIVE', 'SETTLED', 'RELEASED', 'EXPIRED')),
    CONSTRAINT "CK_GOVERNANCE_QUOTA_EXPIRY"
        CHECK ("EXPIRES_AT_EPOCH_MILLIS" >= "CREATED_AT_EPOCH_MILLIS")
);

CREATE INDEX "PUBLIC"."IDX_GOVERNANCE_QUOTA_EXPIRY"
    ON "PUBLIC"."GOVERNANCE_QUOTA_RESERVATION" ("STATUS", "EXPIRES_AT_EPOCH_MILLIS");

CREATE INDEX "PUBLIC"."IDX_GOVERNANCE_QUOTA_TENANT_STATUS"
    ON "PUBLIC"."GOVERNANCE_QUOTA_RESERVATION" ("TENANT_ID", "STATUS");
