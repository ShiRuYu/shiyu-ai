-- Database-level admission reservation.  It closes the check-then-insert
-- race for retries on the same active user message; the row is released when
-- the GenerationRun reaches any terminal state.
CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."CHAT_GENERATION_ACTIVE" (
    "TENANT_ID" BIGINT NOT NULL,
    "CONVERSATION_ID" CHARACTER VARYING(64) NOT NULL,
    "INPUT_MESSAGE_ID" CHARACTER VARYING(64) NOT NULL,
    "GENERATION_ID" CHARACTER VARYING(64) NOT NULL,
    "CREATED_AT" TIMESTAMP NOT NULL,
    CONSTRAINT "PK_CHAT_GENERATION_ACTIVE" PRIMARY KEY ("TENANT_ID", "CONVERSATION_ID", "INPUT_MESSAGE_ID"),
    CONSTRAINT "UK_CHAT_GENERATION_ACTIVE_RUN" UNIQUE ("GENERATION_ID")
);

-- Generation events are a typed projection of AI_RUN_EVENT. Do not create a
-- second physical stream.

CREATE CACHED TABLE IF NOT EXISTS "PUBLIC"."CHAT_IDEMPOTENCY_KEY" (
    "TENANT_ID" BIGINT NOT NULL,
    "OWNER_USER_ID" BIGINT NOT NULL,
    "KEY_VALUE" CHARACTER VARYING(128) NOT NULL,
    "OPERATION" CHARACTER VARYING(64) NOT NULL,
    "RESOURCE_ID" CHARACTER VARYING(64) NOT NULL,
    "CREATED_AT" TIMESTAMP NOT NULL,
    CONSTRAINT "PK_CHAT_IDEMPOTENCY_KEY" PRIMARY KEY ("TENANT_ID", "OWNER_USER_ID", "KEY_VALUE", "OPERATION")
);
