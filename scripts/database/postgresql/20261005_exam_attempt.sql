BEGIN;
UPDATE edu_exam SET del_flag=0 WHERE del_flag IS NULL;
UPDATE edu_course SET del_flag=0 WHERE del_flag IS NULL;
UPDATE edu_question SET del_flag=0 WHERE del_flag IS NULL;
CREATE TABLE IF NOT EXISTS edu_exam_attempt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    exam_id BIGINT NOT NULL,
    student_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    started_at TIMESTAMP NOT NULL,
    deadline_at TIMESTAMP NOT NULL,
    submitted_at TIMESTAMP,
    score DECIMAL(10, 2),
    total_score DECIMAL(10, 2) NOT NULL,
    CONSTRAINT uk_edu_exam_attempt_student UNIQUE (tenant_id, exam_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_exam_attempt_student ON edu_exam_attempt (tenant_id, student_id);
CREATE TABLE IF NOT EXISTS edu_exam_attempt_question (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id BIGINT NOT NULL,
    attempt_id BIGINT NOT NULL,
    exam_question_id BIGINT NOT NULL,
    question_id BIGINT NOT NULL,
    section_id BIGINT NOT NULL,
    section_name VARCHAR(100) NOT NULL,
    section_order_no INTEGER NOT NULL,
    order_no INTEGER NOT NULL,
    title VARCHAR(4000) NOT NULL,
    type VARCHAR(30) NOT NULL,
    options_json TEXT,
    correct_answer TEXT NOT NULL,
    analysis TEXT,
    max_score DECIMAL(10, 2) NOT NULL,
    answer TEXT,
    awarded_score DECIMAL(10, 2),
    CONSTRAINT uk_edu_exam_attempt_question UNIQUE (tenant_id, attempt_id, exam_question_id)
);
CREATE INDEX IF NOT EXISTS idx_exam_attempt_question ON edu_exam_attempt_question (tenant_id, attempt_id);
INSERT INTO auth_auth_code (id, code, name, status, del_flag, create_by, update_by)
SELECT (SELECT COALESCE(MAX(id), 0) + 1 FROM auth_auth_code),
       'edu:exam:take', '参加考试', 1, 0, 'system', 'system'
WHERE NOT EXISTS (SELECT 1 FROM auth_auth_code WHERE code = 'edu:exam:take');
INSERT INTO auth_tenant_auth_code (tenant_id, auth_code_id, status, create_time, update_time)
SELECT t.id, c.id, 1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM auth_tenant t CROSS JOIN auth_auth_code c
WHERE t.id = 1 AND t.status = 1 AND t.del_flag = 0
  AND c.code = 'edu:exam:take' AND c.status = 1 AND c.del_flag = 0
  AND NOT EXISTS (SELECT 1 FROM auth_tenant_auth_code g
                  WHERE g.tenant_id = t.id AND g.auth_code_id = c.id);
INSERT INTO auth_role_scope_auth_code
    (role_id, auth_code_id, tenant_id, status, del_flag, create_by, update_by)
SELECT r.id, c.id, t.id, 1, 0, 'system', 'system'
FROM auth_role r JOIN auth_tenant t ON t.id = r.tenant_id CROSS JOIN auth_auth_code c
WHERE t.id = 1 AND t.status = 1 AND t.del_flag = 0
  AND r.code IN ('super', 'admin', 'user') AND r.status = 1 AND r.del_flag = 0
  AND c.code = 'edu:exam:take' AND c.status = 1 AND c.del_flag = 0
  AND NOT EXISTS (SELECT 1 FROM auth_role_scope_auth_code g
                  WHERE g.role_id = r.id AND g.tenant_id = t.id AND g.auth_code_id = c.id);
COMMIT;
